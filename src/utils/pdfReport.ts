export function printPortfolioReport(
  holdings: PortfolioHolding[],
  stocksMap: Record<string, StockProfile>
): void {
  let totalValue = 0;
  let totalCost = 0;
  let weightedBetaNum = 0;
  let estAnnualDiv = 0;

  const enriched = holdings.map((h) => {
    const st = stocksMap[h.symbol];
    const price = st?.price ?? h.avgCost;
    const value = h.shares * price;
    const cost = h.shares * h.avgCost;
    const pnl = value - cost;
    const pnlPct = cost > 0 ? (pnl / cost) * 100 : 0;
    const beta = st?.beta ?? 1.0;
    const divYield = st?.dividendYield ?? 0;
    totalValue += value;
    totalCost += cost;
    weightedBetaNum += value * beta;
    estAnnualDiv += value * (divYield / 100);
    return { ...h, name: st?.name ?? h.symbol, sector: st?.sector ?? 'Equity', price, value, pnl, pnlPct };
  });

  const totalPnl = totalValue - totalCost;
  const totalPnlPct = totalCost > 0 ? (totalPnl / totalCost) * 100 : 0;
  const portfolioBeta = totalValue > 0 ? weightedBetaNum / totalValue : 1;

  const rowsHtml = enriched
    .map(
      (r) => `<tr>
        <td><strong>${escapeHtml(r.symbol)}</strong> · ${escapeHtml(r.name)}</td>
        <td>${escapeHtml(r.sector)}</td>
        <td class="num">${r.shares.toLocaleString()}</td>
        <td class="num">$${r.avgCost.toFixed(2)}</td>
        <td class="num">$${r.price.toFixed(2)}</td>
        <td class="num">${escapeHtml(formatCurrency(r.value))}</td>
        <td class="num ${r.pnl >= 0 ? 'pos' : 'neg'}">${r.pnl >= 0 ? '+' : ''}${escapeHtml(formatCurrency(r.pnl))} (${r.pnlPct.toFixed(1)}%)</td>
      </tr>`
    )
    .join('');

  const html = `
    <h1>Portfolio Holdings &amp; Risk Summary</h1>
    <div class="kpi-grid">
      <div class="kpi">
        <div class="kpi-label">Total Market Value</div>
        <div class="kpi-val">${escapeHtml(formatCurrency(totalValue))}</div>
        <div class="kpi-sub">${holdings.length} active positions</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">Total Unrealized P&amp;L</div>
        <div class="kpi-val ${totalPnl >= 0 ? 'pos' : 'neg'}">${totalPnl >= 0 ? '+' : ''}${escapeHtml(formatCurrency(totalPnl))}</div>
        <div class="kpi-sub">${totalPnlPct >= 0 ? '+' : ''}${totalPnlPct.toFixed(2)}% total return</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">Weighted Portfolio Beta</div>
        <div class="kpi-val">${portfolioBeta.toFixed(2)}x</div>
        <div class="kpi-sub">Relative to S&amp;P 500</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">Est. Annual Dividends</div>
        <div class="kpi-val">${escapeHtml(formatCurrency(estAnnualDiv))}</div>
        <div class="kpi-sub">${totalValue > 0 ? ((estAnnualDiv / totalValue) * 100).toFixed(2) : '0.00'}% yield on market</div>
      </div>
    </div>

    <h2>Holdings Detail</h2>
    <table>
      <thead>
        <tr>
          <th>Position</th>
          <th>Sector</th>
          <th class="num">Shares</th>
          <th class="num">Avg Cost</th>
          <th class="num">Last Price</th>
          <th class="num">Market Value</th>
          <th class="num">Unrealized P&amp;L</th>
        </tr>
      </thead>
      <tbody>${rowsHtml}</tbody>
    </table>
  `;

  triggerPrintHtml('Meridian Portfolio Risk Summary', html);
}
